func healthHandler(w http.ResponseWriter, r *http.Request) {
	dbStatus := "not_configured"
	redisStatus := "not_configured"
	overallStatus := "healthy"

	// Check Postgres connectivity
	if db != nil {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		defer cancel()
		if err := db.PingContext(ctx); err != nil {
			dbStatus = fmt.Sprintf("unhealthy: %v", err)
			overallStatus = "degraded"
		} else {
			dbStatus = "connected"
		}
	}

	// Check Redis via cache pool health
	if _cachePool != nil {
		cacheSet("__health_ping__", "1", 10)
		if _, ok := cacheGet("__health_ping__"); ok {
			redisStatus = "connected"
		} else {
			redisStatus = "unreachable"
			overallStatus = "degraded"
		}
	}

	jsonResp(w, 200, map[string]interface{}{
		"status": overallStatus,
		"service": "teller-operations-go",
		"checks": map[string]interface{}{
			"database": dbStatus,
			"cache": redisStatus,
		},
	})
}

func listHandler(w http.ResponseWriter, r *http.Request) {
	cacheKey := "teller_operations_list"
	if cached, ok := cacheGet(cacheKey); ok {
		w.Header().Set("Content-Type", "application/json")
		w.Header().Set("X-Cache", "HIT")
		w.WriteHeader(200)
		w.Write([]byte(cached))
		return
	}
	if db == nil {
		jsonResp(w, 200, map[string]interface{}{"items": []interface{}{}, "total": 0, "source": dbSourceTag()})
		return
	}
	page, _ := strconv.Atoi(r.URL.Query().Get("page"))
	if page < 1 { page = 1 }
	limit, _ := strconv.Atoi(r.URL.Query().Get("limit"))
	if limit < 1 { limit = 50 }
	offset := (page - 1) * limit
	rows, err := db.Query("SELECT id, type, status, data, created_at FROM service_records WHERE service=$1 ORDER BY created_at DESC LIMIT $2 OFFSET $3", "teller-operations-go", limit, offset)
	if err != nil {
		jsonResp(w, 500, map[string]interface{}{"error": err.Error()})
		return
	}
	defer rows.Close()
	items := []interface{}{}
	for rows.Next() {
		var id, typ, status, data, ts string
		if err := rows.Scan(&id, &typ, &status, &data, &ts); err != nil { continue }
		items = append(items, map[string]interface{}{"id": id, "type": typ, "status": status, "data": data, "createdAt": ts})
	}
	var total int
	db.QueryRow("SELECT COUNT(*) FROM service_records WHERE service=$1", "teller-operations-go").Scan(&total)
	jsonResp(w, 200, map[string]interface{}{"items": items, "total": total, "page": page, "limit": limit, "source": "database"})
}

